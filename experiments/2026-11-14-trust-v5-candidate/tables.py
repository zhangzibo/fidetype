"""P5-07: tables (results/tables.md) and the pre-declared criteria check (results/criteria.json) from results/*.json."""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE / "results"
ALPHA = 0.05
ARMS = ["v4", "v5", "v5 - a (no gate)", "v5 - b (v4 grid rule)", "v5 - d (no floor)", "v5 + c (0.8 for 1.0)",
        "v4 + a", "v4 + b", "v4 + c", "v4 + d", "never commit"]
SIGNAL_DESTROYING = ("uniform", "frame_shuffled", "zero_standin", "zero_input", "shuffled_meg")


def load(name):
    p = OUT / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fixed_sets() -> list[tuple[str, dict, bool]]:
    """(label, eval dict, real data?)"""
    out = []
    for which in ("ours", "published"):
        r = load(f"b2t-{which}.json")
        for sp, ev in ((r or {}).get("splits") or {}).items():
            out.append((f"B2T {which} {sp}", ev, True))
    r = load("emg.json")
    for c, ev in ((r or {}).get("conditions") or {}).items():
        out.append((f"sEMG {c[4:]}", ev, True))
    for part in ("val", "pool"):
        r = load(f"t12-{part}.json")
        if r:
            out.append((f"T12 {part}", r, True))
    for name in ("meg-a.json", "meg-b.json", "meg.json"):
        r = load(name)
        for run, ev in ((r or {}).get("runs") or {}).items():
            out.append((f"MEG {run.replace('m1-09-', '')}", ev, True))
    for name in ("sim-median.json", "sim-worst.json"):
        r = load(name)
        for c, ev in ((r or {}).get("conditions") or {}).items():
            out.append((f"sim {c}", ev, False))
    return out


def f4(x):
    return "—" if x is None else f"{x:.4f}"


def cell(v: dict) -> str:
    return f"{v['n_wrong_commit']}/{v['n_commit']} · {v['ewpm']:.2f}"


def ctl_max(ev: dict, arm: str) -> tuple[int, int, str]:
    """(commits, n, kind) of the worst signal-destroying control for ``arm``."""
    best = (0, 1, "-")
    for k, d in (ev.get("controls") or {}).items():
        if k in SIGNAL_DESTROYING and arm in d:
            c = d[arm]
            if c["n_commit"] / c["n"] > best[0] / best[1] or best[2] == "-":
                best = (c["n_commit"], c["n"], k)
    return best


def main() -> None:
    sets = fixed_sets()
    L = ["# P5-07 tables (generated by tables.py)", "",
         "Cells: wrong commits / commits · eWPM on the test set. **Bold** = Holm-corrected exact McNemar p < 0.05 vs v4.", ""]
    # main table
    L += ["## 1. Fixed splits: all arms", "", "| set | n | " + " | ".join(ARMS) + " |", "|" + "---|" * (len(ARMS) + 2)]
    for lab, ev, _ in sets:
        row = [lab, str(ev["n_test"])]
        for a in ARMS:
            v = ev["arms"].get(a)
            if v is None:
                row.append("—")
                continue
            s = cell(v)
            if (v.get("vs_v4") or {}).get("p_holm", 1) < 0.05:
                s = f"**{s}**"
            row.append(s)
        L.append("| " + " | ".join(row) + " |")
    # controls
    L += ["", "## 2. Signal-destroying test-time controls (worst kind; commits / n)", "",
          "| set | " + " | ".join(ARMS[:-1]) + " | empty commits v4 / v5 (all sets) |", "|" + "---|" * (len(ARMS) + 1)]
    for lab, ev, _ in sets:
        row = [lab]
        for a in ARMS[:-1]:
            c, n, k = ctl_max(ev, a)
            row.append(f"{c}/{n} ({k})" if k != "-" else "—")
        e4 = ev["arms"]["v4"]["n_empty_commit"] + sum(d["v4"]["n_empty_commit"] for d in (ev.get("controls") or {}).values())
        e5 = ev["arms"]["v5"]["n_empty_commit"] + sum(d["v5"]["n_empty_commit"] for d in (ev.get("controls") or {}).values())
        row.append(f"{e4} / {e5}")
        L.append("| " + " | ".join(row) + " |")
    L += ["", "### Per kind, v4 vs v5 (commits / n)", "", "| set | kind | v4 | v5 | v5 − d | v5 − b | v4 + a |", "|---|---|---|---|---|---|---|"]
    for lab, ev, _ in sets:
        for k, d in (ev.get("controls") or {}).items():
            L.append(f"| {lab} | {k} | " + " | ".join(f"{d[a]['n_commit']}/{d[a]['n']}" for a in
                                                      ("v4", "v5", "v5 - d (no floor)", "v5 - b (v4 grid rule)", "v4 + a")) + " |")
    # selections
    L += ["", "## 3. Grid selections and lambda parts", "",
          "| set | v4 (commit_p / max_risk) | v5 selection | v4 λ (grid, LTT) | v5 λ (grid, LTT, floor) | fit-time control rates at v4 point (uni / fs / zero) |",
          "|---|---|---|---|---|---|"]
    for lab, ev, _ in sets:
        s4, s5 = ev["selections"]["v4"], ev["selections"]["aware_g"]
        l4, l5 = ev["arms"]["v4"]["lambda_parts"], ev["arms"]["v5"]["lambda_parts"]
        cr = s4["fit_control_rates_nogate"]
        L.append(f"| {lab} | {s4['policy']['commit_p']} / {s4['policy']['commit_max_risk']} | {s5['policy']['commit_p']} / "
                 f"{s5['policy']['commit_max_risk']} | {l4['grid']}, {l4['ltt']} | {l5['grid']}, {l5['ltt']}, {l5['floor']} | "
                 f"{cr.get('uniform', 0):.3f} / {cr.get('frame_shuffled', 0):.3f} / {cr.get('zero_standin', 0):.3f} |")
    # stability
    L += ["", "## 4. Stability (200 bootstrap resamples of the grid-fit set)", "",
          "| set | v4 rule: share max_risk 1.0 | v4: top point (share) | v4: distinct | v5 rule: share 1.0 | v5: top point (share) | v5: distinct |",
          "|---|---|---|---|---|---|---|"]
    for lab, ev, _ in sets:
        st = ev.get("stability")
        if not st:
            continue
        a, b = st["v4 rule"], st["v5 rule"]
        one = lambda d: max((v for k, v in d["share_commit_max_risk"].items() if float(k) >= 1.0), default=0.0)  # noqa: E731
        L.append(f"| {lab} | {one(a):.2f} | {a['top_point']} ({a['share_top_point']:.2f}) | {a['n_distinct_points']} | "
                 f"{one(b):.2f} | {b['top_point']} ({b['share_top_point']:.2f}) | {b['n_distinct_points']} |")
    # repeated splits
    sp = load("splits.json") or {}
    L += ["", "## 5. Repeated splits (refitted)", "", "| condition | R | arm | share > α [CP95] | mean wrong-commit | mean commit | mean eWPM | up / down vs v4 | empty commits |",
          "|---|---|---|---|---|---|---|---|---|"]
    for cond, d in sp.items():
        if cond == "env":
            continue
        for a in ARMS:
            if a not in d:
                continue
            v = d[a]
            ci = v["share_gt_alpha_cp95"]
            L.append(f"| {cond} | {d['R']} | {a} | {v['share_gt_alpha']:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] | {v['wrong_commit_mean']:.4f} | "
                     f"{v['commit_rate_mean']:.3f} | {v['ewpm_mean']:.2f} | {v['n_up']} / {v['n_down']} | {v['n_empty_commit']} |")
        L.append(f"| {cond} | | selection max_risk shares | " + "; ".join(f"{k}: {v}" for k, v in d["selection_commit_max_risk_share"].items()) + " | | | | | |")
    # small fit sets
    L += ["", "## 6. B2T split A with 240-trial fit sets (10 draws)", "", "| decoder | arm | median eWPM | min eWPM | median rel. eWPM change vs v4 | wrong / commits (sum) | draws with eWPM < never − 0.05 |",
          "|---|---|---|---|---|---|---|"]
    for which in ("ours", "published"):
        r = load(f"b2t-small-{which}.json")
        if not r:
            continue
        dr = list(r["draws"].values())
        for a in ARMS:
            e = np.array([x["arms"][a]["ewpm"] for x in dr])
            e4 = np.array([x["arms"]["v4"]["ewpm"] for x in dr])
            nv = np.array([x["arms"]["never commit"]["ewpm"] for x in dr])
            L.append(f"| {which} | {a} | {np.median(e):.2f} | {e.min():.2f} | {np.median((e - e4) / e4):+.3f} | "
                     f"{sum(x['arms'][a]['n_wrong_commit'] for x in dr)} / {sum(x['arms'][a]['n_commit'] for x in dr)} | {int((e < nv - 0.05).sum())} |")
    # declaration
    L += ["", "## 7. Declaration check (e): raw-decoding producer vs the frozen v5 configuration", "",
          "| set | mode | commits | wrong | eWPM | actions |", "|---|---|---|---|---|---|"]
    for lab, ev, _ in sets:
        e2e = ev.get("end_to_end")
        if not e2e:
            continue
        for mode, v in e2e["declaration"].items():
            L.append(f"| {lab} | {mode} | {v['n_commit']} | {v['n_wrong_commit']} | {v['ewpm']:.2f} | {v.get('actions')} |")
    L += ["", "### End-to-end checks (library `fit_trust_v5` + `freeze_v5` + streaming layer)", "",
          "| set | lib commit_p = arm λ | lib policy = arm policy | commits lib / arm | streaming = batch | v5 config id |", "|---|---|---|---|---|---|"]
    for lab, ev, _ in sets:
        e2e = ev.get("end_to_end")
        if not e2e:
            continue
        eq = e2e.get("stream_equal_to_batch_with_gate", (e2e.get("stream_matched") or {}).get("equal_to_batch_with_gate"))
        L.append(f"| {lab} | {e2e['lib_commit_p_equals_arm']} | {e2e['lib_policy_equals_arm']} | {e2e['lib_n_commit']} / {e2e['arm_n_commit']} | "
                 f"{eq}/{e2e.get('n', ev['n_test'])} | `{e2e['config_id_v5']}` |")
    (OUT / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    criteria(sets, sp)


def criteria(sets, sp) -> None:
    c: dict = {}
    s1 = []
    for lab, ev, real in sets:
        if real:
            v = ev["arms"]["v5"]
            vs = v["vs_v4"]
            worse = vs["d_wrong_commit"] > 0 and vs.get("p_holm", 1) < 0.05
            s1.append({"set": lab, "d_wrong_commit": vs["d_wrong_commit"], "p_holm": vs.get("p_holm"), "fail": bool(worse)})
    rs = []
    for cond, d in sp.items():
        if cond == "env":
            continue
        rs.append({"cond": cond, "v4": d["v4"]["share_gt_alpha"], "v5": d["v5"]["share_gt_alpha"],
                   "fail": bool(d["v5"]["share_gt_alpha"] > d["v4"]["share_gt_alpha"] + 0.05 + 1e-12)})
    c["S1"] = {"fixed": s1, "splits": rs, "pass": not any(x["fail"] for x in s1 + rs)}
    e = []
    for lab, ev, _ in sets:
        n = ev["arms"]["v5"]["n_empty_commit"] + sum(d["v5"]["n_empty_commit"] for d in (ev.get("controls") or {}).values())
        e.append({"set": lab, "n_empty_commit": n})
    e_sp = {cond: d["v5"]["n_empty_commit"] for cond, d in sp.items() if cond != "env"}
    c["S2"] = {"fixed": e, "splits": e_sp, "pass": all(x["n_empty_commit"] == 0 for x in e) and all(v == 0 for v in e_sp.values())}
    s3 = []
    for lab, ev, _ in sets:
        for k, d in (ev.get("controls") or {}).items():
            if k in SIGNAL_DESTROYING:
                x = d["v5"]
                s3.append({"set": lab, "kind": k, "n_commit": x["n_commit"], "n": x["n"], "fail": x["n_commit"] / x["n"] > 0.01 + 1e-12})
    c["S3"] = {"rows": s3, "fails": [x for x in s3 if x["fail"]], "pass": not any(x["fail"] for x in s3)}
    s4 = []
    for lab, ev, _ in sets:
        if lab.startswith("T12"):
            s4.append({"set": lab, "v5": ev["arms"]["v5"]["ewpm"], "never": ev["arms"]["never commit"]["ewpm"],
                       "fail": ev["arms"]["v5"]["ewpm"] < ev["arms"]["never commit"]["ewpm"] - 0.05})
    med = {}
    for which in ("ours", "published"):
        r = load(f"b2t-small-{which}.json")
        if not r:
            continue
        dr = list(r["draws"].values())
        e5 = np.array([x["arms"]["v5"]["ewpm"] for x in dr])
        e4 = np.array([x["arms"]["v4"]["ewpm"] for x in dr])
        nv = np.array([x["arms"]["never commit"]["ewpm"] for x in dr])
        med[which] = {"median_rel_change": float(np.median((e5 - e4) / e4)), "n_below_never": int((e5 < nv - 0.05).sum()),
                      "n_draws": len(dr)}
    c["S4"] = {"t12": s4, "b2t240": med,
               "pass": not any(x["fail"] for x in s4) and all(m["n_below_never"] == 0 and m["median_rel_change"] >= -0.10 for m in med.values())}
    s5 = []
    for lab, ev, real in sets:
        if real:
            a4, a5 = ev["arms"]["v4"]["ewpm"], ev["arms"]["v5"]["ewpm"]
            s5.append({"set": lab, "v4": a4, "v5": a5, "rel": (a5 - a4) / a4 if a4 else math.nan})
    s5s = {cond: {"v4": d["v4"]["ewpm_mean"], "v5": d["v5"]["ewpm_mean"],
                  "rel": (d["v5"]["ewpm_mean"] - d["v4"]["ewpm_mean"]) / d["v4"]["ewpm_mean"]} for cond, d in sp.items() if cond != "env"}
    c["S5"] = {"fixed": s5, "splits": s5s}
    (OUT / "criteria.json").write_text(json.dumps(c, indent=1) + "\n", encoding="utf-8")
    print({k: v.get("pass") for k, v in c.items()})


if __name__ == "__main__":
    main()
