"""Build results/tables.md from the results/*.json files (aggregated numbers only).

Run (repo root): .venv/Scripts/python.exe -I experiments/2026-11-14-m3-01-02-ablations/tables.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "results"
SIGNAL_DESTROYING = ("frame_shuffled", "uniform", "zero_input", "zero_standin", "shuffled_meg")


def load(name):
    p = OUT / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, nd=4):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "—"
    if isinstance(x, str):
        return x
    return f"{x:.{nd}f}"


def lam(x):
    if isinstance(x, str):
        return {"inf": "+inf", "-inf": "−inf"}.get(x, x)
    return f(x, 2)


def wc_cell(r):
    k, n = r["n_wrong_commit"], r["n"]
    if k == 0:
        return f"0/{n} (≤ {r['wrong_commit_cp95_one_sided_upper']:.4f})"
    lo, hi = r["wrong_commit_cp95"]
    return f"{k}/{n} = {r['wrong_commit']:.4f} [{lo:.3f}, {hi:.3f}]"


def ctl_cell(ctl: dict | None, arm: str):
    if not ctl or arm not in ctl:
        return "", ""
    d = ctl[arm]
    sd = [f"{c.replace('_', ' ')} {v['n_commit']}/{v['n']}" for c, v in d.items() if c in SIGNAL_DESTROYING]
    im = d.get("intent_mismatch")
    return "; ".join(sd), (f"{im['n_commit']}/{im['n']}" if im else "")


def arm_table(rows: dict, ctl: dict | None = None, gaze: float | None = None) -> list[str]:
    L = ["| arm | λ | wrong-commit k/n [CP95] | commit | eWPM | Δ wrong-commit vs v4 | Δ eWPM vs v4 | McNemar p (Holm) | "
         "signal-destroying controls: commits/n | intent mismatch commits |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for arm, r in rows.items():
        if r is None:
            continue
        v = r.get("vs_v4") or {}
        p = f"{v['p']:.3g} ({v.get('p_holm', float('nan')):.3g})" if v else ""
        sd, im = ctl_cell(ctl, arm)
        d_wc = f"{v['d_wrong_commit']:+.4f}" if v else ""
        d_e = f"{v['d_ewpm']:+.2f}" if v else ""
        extra = ""
        info = r.get("info") or {}
        if "n_alarms" in info:
            extra = f" ({info['n_alarms']}/{info['n_sessions']} sessions alarmed)"
        if "n_blocked" in info:
            extra = f" ({info['n_blocked']} commits blocked)"
        L.append(f"| {arm}{extra} | {lam(r.get('lambda', '—'))} | {wc_cell(r)} | {r['commit_rate']:.3f} | {f(r.get('ewpm'), 2)} | "
                 f"{d_wc} | {d_e} | {p} | {sd} | {im} |")
    if gaze is not None:
        L.append(f"| gaze typing only | — | 0 | 0 | {gaze:.2f} | | | | | |")
    return L


def split_table(d: dict) -> list[str]:
    L = ["| arm | wrong-commit mean (p05–p95) | splits > α [CP95] | commit | eWPM | Δ mean wrong-commit vs v4 | splits up / down vs v4 (sign p) |",
         "|---|---|---|---|---|---|---|"]
    for arm, r in d.items():
        if not isinstance(r, dict):
            continue
        cp = r["share_gt_alpha_cp95"]
        L.append(f"| {arm} | {r['wrong_commit_mean']:.4f} ({r['p05']:.3f}–{r['p95']:.3f}) | {r['share_gt_alpha']:.3f} "
                 f"[{cp[0]:.3f}, {cp[1]:.3f}] | {r['commit_rate_mean']:.3f} | {r['ewpm_mean']:.2f} | {r['d_wrong_commit_mean']:+.4f} | "
                 f"{r['n_up']} / {r['n_down']} ({r['sign_test_p']:.2g}) |")
    return L


def main() -> None:
    L = ["# M3-01 / M3-02 tables (generated by tables.py)", "",
         "Wrong-commit = wrong commits / all test items, exact two-sided Clopper-Pearson 95 % interval (zero counts: one-sided 95 % upper bound). "
         "eWPM from the harness simulated user. McNemar: exact, paired on the per-item wrong-commit indicator vs v4; Holm over the arms of one table. "
         "Controls: Paper 1 audit draws (B2T split A only).", ""]
    for which in ("ours", "published"):
        r = load(f"b2t-{which}.json")
        if not r:
            continue
        for sp, d in r["splits"].items():
            L += [f"## B2T '25 T15, {which} decoder, fixed split {sp}", "",
                  f"Frame T (cal on / off): {d['T']['c1g1']:.4f} / {d['T']['c0g1']:.4f}. Gate B would block {d['gate_blocked_test_items']} test items.", ""]
            L += arm_table(d["rows"], r.get("controls") if sp == "A" else None)
            L.append("")
        if "declaration_stream" in r:
            L += [f"Declaration check through `StreamingTrustLayer` (hypothesis route, {which}, split A, 816 trials):", "",
                  "| hypotheses | check | commits | wrong commits | eWPM | declared mismatches | commits equal to batch |", "|---|---|---|---|---|---|---|"]
            for k, v in r["declaration_stream"].items():
                hyp, chk = k.split(", check ")
                L.append(f"| {hyp} | {chk} | {v['n_commit']} | {v['n_wrong_commit']} | {v['ewpm']:.2f} | {v['n_declaration_mismatch']} | "
                         f"{v['commit_equal_to_batch']}/{v['n']} |")
            L.append("")
    e = load("emg.json")
    if e:
        for c, d in e["conditions"].items():
            L += [f"## Toronto sEMG, {c}, fixed split", "", f"Frame T (cal on): {d['T']['c1g1']:.4f}.", ""]
            L += arm_table(d["rows"], d.get("controls"))
            L.append("")
    s = load("splits.json")
    if s:
        for c, d in s.items():
            if c == "env":
                continue
            L += [f"## Repeated splits: {c} (R = {d['R']}, cached Paper 1 tables)", ""]
            L += split_table(d)
            L.append("")
    meg_runs: dict = {}
    for name in ("meg.json", "meg-seeds.json", "meg-other.json"):
        m = load(name)
        if m:
            meg_runs.update(m["runs"])
    if meg_runs:
        for run, d in meg_runs.items():
            ds = d["decoder_test"]
            L += [f"## SpanishBCBL MEG (CC BY-NC 4.0, aggregated), run {run}", "",
                  f"fit-A {d['n_fitA']}, calibration {d['n_cal']}, test {d['n_test']} ({d['n_participants_test']} participants). "
                  f"Decoder on test (calibrated): top-1 sentence correct {ds['n_top1_correct']}/{ds['n']} ({ds['top1_sentence_acc']:.3f}), "
                  f"top-1 CER {ds['top1_cer_mean']:.3f}, truth in n-best {ds['n_truth_in_nbest']}/{ds['n']}. "
                  f"Calibration set: {d['cal_wrong_if_all_commit']} of {d['cal_eligible']} eligible top-1 wrong.", ""]
            L += arm_table(d["rows"], d.get("controls"), d.get("gaze_ewpm"))
            st = d["stream"]
            L += ["", f"Streaming layer (frames route, frozen `{st['config_id']}`): commits {st['n_commit']}, wrong {st['n_wrong_commit']}, "
                  f"eWPM {st['ewpm']:.2f}, commit decision equal to batch {st['commit_equal_to_batch']}/{st['n']}; with gate B: commits "
                  f"{d['stream_gate']['n_commit']}.", ""]
    for name in ("sim-median.json", "sim-worst.json"):  # noqa
        sm = load(name)
        if not sm:
            continue
        for c, d in sm["conditions"].items():
            st = d["stream"]
            L += [f"## Simulator {c}", "", f"Frame T (cal on): {d['T']['c1g1']:.3f}. Streaming (frames route, `{st['config_id']}`): commits "
                  f"{st['n_commit']}, wrong {st['n_wrong_commit']}, eWPM {st['ewpm']:.2f}, equal to batch {st['commit_equal_to_batch']}/{st['n']}.", ""]
            L += arm_table(d["rows"], d.get("controls"))
            L.append("")
    (OUT / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT / "tables.md")


if __name__ == "__main__":
    main()
