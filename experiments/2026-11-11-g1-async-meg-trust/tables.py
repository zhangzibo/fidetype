"""Write results/tables.md from the G1 JSON files (run after run.py)."""

from __future__ import annotations

import json
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent / "results"
SC = ("trials", "sentences", "participants", "two_way")
NAMES = {"commit": "always commit LM top-1", "trust": "trust", "trust_ow": "trust + OFFER_WORDS",
         "trust_silent": "trust, silent-error limit", "trust_ow_silent": "trust + OW, silent-error limit",
         "ow_all": "OFFER_WORDS always", "gaze_only": "gaze typing only (no BCI)"}


def load(name):
    p = OUT / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(v, nd=2):
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return "—"
    return f"{v:.{nd}f}" if isinstance(v, (int, float)) else str(v)


def ci(c, nd=2):
    return "—" if not c else f"[{f(c[0], nd)}, {f(c[1], nd)}]"


def harness_tables(h, L):
    b = h["bootstrap"]
    L += [f"## eWPM harness: {h['streams']} ({h['n_test']} test instances, {h['n_test_sentences']} sentences, "
          f"{h['n_test_participants']} participants; fit on {h['n_val']} val)", "",
          "eWPM point, then 95 % percentile CIs: trials / unique-sentence clusters / participant clusters / "
          "two-way (sentences x participants).", "",
          "| policy | eWPM | CI trials | CI sentences | CI participants | CI two-way | wrong-commit [CI sentences] | silent error | KSR | COMMIT | OFFER | OFFER_WORDS |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for p, r in h["policies"].items():
        cs = [b[s]["policies"].get(p, {}).get("ewpm") for s in SC]
        wc = b["sentences"]["policies"].get(p, {}).get("wrong_commit_rate")
        L.append(f"| {NAMES.get(p, p)} | {f(r['ewpm'], 3)} | " + " | ".join(ci(c) for c in cs) +
                 f" | {f(r.get('wrong_commit_rate'), 3)} {ci(wc, 3)} | {f(r.get('silent_error_rate'), 3)} | "
                 f"{f(r.get('keystrokes_saved'), 3)} | {f(r.get('rate_commit'))} | {f(r.get('rate_offer'))} | "
                 f"{f(r.get('rate_offer_words'))} |")
    L += ["", "Paired eWPM differences (95 % CI; P(diff <= 0) in parentheses):", "",
          "| difference | trials | sentences | participants | two-way |", "|---|---|---|---|---|"]
    for d in b["trials"]["diffs"]:
        cells = []
        for s in SC:
            x = b[s]["diffs"][d]["ewpm"]
            cells.append(f"{ci(x['ci'])} ({x['p_le_0']:.3f})")
        L.append(f"| {d} | " + " | ".join(cells) + " |")
    nb = h.get("nbest", {})
    L += ["", f"True sentence at rank 1: {f(nb.get('top1_sentence_acc'), 4)}; in the 10-best: {f(nb.get('in_nbest'), 4)}.", ""]
    if "sensitivity" in h:
        L += ["### User-model sensitivity (refit per variant)", "",
              "| variant | commit | trust | trust_ow | gaze only | trust − gaze [CI sentences] | trust − gaze [CI participants] |",
              "|---|---|---|---|---|---|---|"]
        for v, d in h["sensitivity"].items():
            p = d["policies"]
            L.append(f"| {v} | {f(p['commit']['ewpm'])} | {f(p['trust']['ewpm'])} | {f(p['trust_ow']['ewpm'])} | "
                     f"{f(d['gaze_only_ewpm'])} | {ci(d['diffs_ewpm']['sentences']['trust-gaze_only']['ci'])} | "
                     f"{ci(d['diffs_ewpm']['participants']['trust-gaze_only']['ci'])} |")
        L.append("")
    pp = h.get("per_participant")
    if pp:
        L += ["### Per participant (test eWPM)", "", "| participant | n | commit | trust | trust_ow | gaze only | trust − gaze |",
              "|---|---|---|---|---|---|---|"]
        g = pp.get("_gaze_only", {})
        for k, v in pp.items():
            if k.startswith("_"):
                continue
            L.append(f"| {k} | {v['n']} | {f(v['commit']['ewpm'])} | {f(v['trust']['ewpm'])} | {f(v['trust_ow']['ewpm'])} | "
                     f"{f(g.get(k))} | {f(v['trust']['ewpm'] - g.get(k, float('nan')), 2)} |")
        L.append("")


def main():
    L = ["# G1 tables (generated by tables.py)", ""]
    for s in ("async", "sync"):
        h = load(f"harness-{s}.json")
        if h:
            harness_tables(h, L)
    a = load("null-audit-async.json")
    if a:
        L += [f"## Null-input audit (async, {a['n']} test instances)", "",
              "| policy | input | fluent top-1 | COMMIT | fluent and committed | wrong commit | OFFER_WORDS | guard-risk AUROC null vs real |",
              "|---|---|---|---|---|---|---|---|"]
        for p, d in a["policies"].items():
            au = d.get("risk_auroc_null_vs_real", {})
            for c, v in d.items():
                if c == "risk_auroc_null_vs_real":
                    continue
                L.append(f"| {p} | {c} | {f(v['fluent_rate'], 3)} | {f(v['commit_rate'], 3)} | {f(v['fluent_commit_rate'], 3)} | "
                         f"{f(v['wrong_commit_rate'], 3)} | {f(v['offer_words_rate'], 3)} | {f(au.get(c), 3)} |")
        L.append("")
    c = load("crc-splits-async.json")
    if c:
        L += [f"## CRC / LTT (async; alpha {c['alpha']}, delta {c['delta']}, {c['reps']} splits per protocol)", "",
              f"Test {c['n_test']}; old commit_p {c['lam_old']}; eligible {c['eligible_rate']:.3f}; top-1 right {c['top1_right_rate']:.4f}.", "",
              "| protocol | method | wrong-commit mean ± se | p95 | P(> alpha) | commit rate | eWPM mean [p05, p95] | never-commit share |",
              "|---|---|---|---|---|---|---|---|"]
        for lab, rows in c["splits"].items():
            for k, v in rows.items():
                if k.startswith("_"):
                    continue
                L.append(f"| {lab} (n_cal ≈ {rows['_n_cal_mean']:.0f}) | {k} | {v['wrong_commit']['mean']:.4f} ± {v['wrong_commit']['se']:.4f} | "
                         f"{v['wrong_commit']['p95']:.4f} | {v['p_exceed_alpha']:.2f} | {v['commit_rate']['mean']:.3f} | "
                         f"{v['ewpm']['mean']:.3f} [{v['ewpm']['p05']:.3f}, {v['ewpm']['p95']:.3f}] | {v['never_commit_share']:.2f} |")
        L += ["", "One shot, calibrate on val (437), test on all 637:", "", "| method | commit_p | wrong-commit | commit rate | eWPM |", "|---|---|---|---|---|"]
        for k, v in c["earlier_data"].items():
            L.append(f"| {k} | {v['threshold']} | {v['wrong_commit']:.4f} | {v['commit_rate']:.3f} | {v['ewpm']:.3f} |")
        L.append("")
    o = load("online-async.json")
    if o:
        L += [f"## Online re-calibration (async, M2-16 drift protocol: warm start on val, test in participant order)", "",
              "| method | wrong-commit | max rolling-50 | commit rate | eWPM |", "|---|---|---|---|---|"]
        for k, m in o["drift"]["offline"].items():
            L.append(f"| offline {k} | {m['wrong_commit']:.4f} | {f(m.get('roll_max'), 3)} | {m['commit_rate']:.3f} | {m['ewpm']:.3f} |")
        for k, m in o["drift"]["online"].items():
            L.append(f"| {k} | {m['wrong_commit']:.4f} | {f(m.get('roll_max'), 3)} | {m['commit_rate']:.3f} | {m['ewpm']:.3f} |")
        L.append("")
    (OUT / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
