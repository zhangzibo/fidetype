"""Paper 1, draft v4: write the supplementary LaTeX tables from committed result files only.

Every number is read from a committed JSON file of the round-4 analyses
(experiments/2026-11-12-paper1-r4-analyses/) and formatted; nothing is
computed here except rounding and counting. Output: papers/paper1/latex/generated/*.tex

Run (repo root):  .venv/Scripts/python -I papers/paper1/make_supp_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
R4 = REPO / "experiments/2026-11-12-paper1-r4-analyses"
OUT = Path(__file__).resolve().parent / "latex" / "generated"
OUT.mkdir(parents=True, exist_ok=True)


def load(rel: str) -> dict:
    return json.loads((R4 / rel).read_text(encoding="utf-8"))


def f(x, d=3) -> str:
    return "---" if x is None else f"{x:.{d}f}"


def ci(a, d=3) -> str:
    return f"\\ci{{{a[0]:.{d}f}}}{{{a[1]:.{d}f}}}"


def sgn(x, d=4) -> str:
    return f"${x:+.{d}f}$"


def pv(x) -> str:
    if x >= 0.001:
        return f"{x:.2g}"
    m, e = f"{x:.1e}".split("e")
    return f"${m}" + r"\times 10^{" + f"{int(e)}" + "}$"


def write(name: str, body: str) -> None:
    (OUT / f"{name}.tex").write_text("% generated by papers/paper1/make_supp_tables.py -- do not edit by hand\n" + body, encoding="utf-8")


# ---------------------------------------------------------------- forward chain, all designs and rules
def tab_forward() -> None:
    d = load("forward-chain/results/forward_chain.json")["conditions"]
    rules = ["plug-in", "CRC pure", "CRC max", "LTT max", "joint LTT b0.10", "joint LTT b0.20"]
    vnames = {"V1 previous day": "V1", "V4 two previous days": "V4", "V2 fixed fit D1-D3, all earlier days": "V2",
              "V3 session start (first half of the test day)": "V3"}
    cnames = {"b2t-ours/guard": "ours, guard", "b2t-ours/no guard": "ours, no guard",
              "b2t-published/guard": "published, guard", "b2t-published/no guard": "published, no guard"}
    L = []
    for c, cn in cnames.items():
        for v, vn in vnames.items():
            s = d[c]["variants"][v]["summary"]
            cells = []
            for r in rules:
                x = s[r]
                cells.append(f"{x['days_above_alpha']}/{x['n_days']}, {x['pooled_wrong_commit']:.3f} ({x['pooled_commit_rate']:.2f})")
            L.append(f"{cn} & {vn} & " + " & ".join(cells) + r" \\")
    write("tab_forward_full", "\n".join(L) + "\n")


# ---------------------------------------------------------------- per day
def tab_perday() -> None:
    d = load("per-day/results/per_day.json")
    days = list(d["repeated"]["b2t-ours/R50"]["rules"]["LTT max"].keys())
    L = []
    for day in days:
        o = d["repeated"]["b2t-ours/R50"]["rules"]["LTT max"][day]
        p = d["repeated"]["b2t-published/R50"]["rules"]["LTT max"][day]
        p2 = d["repeated"]["b2t-published/R200"]["rules"]["LTT max"][day]
        fa = d["fixed"]["b2t-ours/split A"][day]["LTT max"]
        pa = d["fixed"]["b2t-published/split A"][day]["LTT max"]
        pb = d["fixed"]["b2t-published/split B"][day]["LTT max"]
        bold = p["pooled"] > 0.05
        pp = f"\\textbf{{{p['pooled']:.3f}}}" if bold else f"{p['pooled']:.3f}"
        L.append(f"{day} & {o['n_test_mean']:.0f} & {o['pooled']:.3f} & {o['share_gt_alpha']:.2f} & {pp} ({p['p05']:.3f}--{p['p95']:.3f}) & "
                 f"{p['share_gt_alpha']:.2f} & {p2['pooled']:.3f} & {fa['n_wrong']}/{fa['n']} & {pa['n_wrong']}/{pa['n']} & {pb['n_wrong']}/{pb['n']} \\\\")
    write("tab_perday", "\n".join(L) + "\n")


# ---------------------------------------------------------------- reuse, 12 comparisons
def tab_reuse() -> None:
    r = load("reuse/results/reuse.json")["families"]["R50"]
    names = {"b2t-ours": "B2T '25 ours", "b2t-published": "B2T '25 published", "emg-calib": "sEMG session-cal.",
             "emg-xsession": "sEMG cross-session"}
    L = []
    for k, x in r.items():
        cond, rule = [s.strip() for s in k.split("/")]
        st = x["sign_test_splits"]
        jk = x["jackknife"]
        L.append(f"{names[cond]} & {rule} & {sgn(x['mean_diff'])} & {pv(x['wilcoxon_p_splits'])} ({pv(x['wilcoxon_holm_splits'])}) & "
                 f"{st['positive']}/{st['negative']} & \\ci{{{jk['ci95'][0]:+.4f}}}{{{jk['ci95'][1]:+.4f}}} & "
                 f"{pv(x['jackknife_p'])} ({pv(x['jackknife_holm'])}) \\\\")
    write("tab_reuse", "\n".join(L) + "\n")


# ---------------------------------------------------------------- published-gate bonus
def tab_bonus() -> None:
    b = load("bonus-sensitivity/results/bonus.json")
    L = []
    for m in ("margin 0", "margin 0.5", "margin 1", "margin 2", "margin 4"):
        x = b[m]
        ff = x["full_fit"]["point"]["plug-in"]
        ffc = x["full_fit"]["ci"]["plug-in"]["wrong_commit"]
        a = x["split A"]["point"]["LTT max"]
        bb = x["split B"]["point"]["LTT max"]
        rp = b["repeated"][m]["rules"]["LTT max"]
        lab = m.replace("margin ", "") + (" (paper)" if m == "margin 2" else "")
        L.append(f"{lab} & {ff['wrong_commit']:.4f} {ci(ffc)} & {ff['commit_rate']:.2f} & {ff['ewpm']:.2f} & "
                 f"{a['wrong_commit']:.4f} ({a['commit_rate']:.2f}) & {bb['wrong_commit']:.4f} ({bb['commit_rate']:.2f}) & "
                 f"{rp['wrong_commit_mean']:.4f}, {rp['share_gt_alpha']:.2f} ({rp['commit_rate_mean']:.2f}) \\\\")
    pa = b["published alone"]
    L.append(r"published sentence alone & 0 commits & 0 & " + f"{pa['full_fit']['point']['plug-in']['ewpm']:.2f}" if isinstance(pa, dict) and "full_fit" in pa else r"published sentence alone & 0 commits & 0 & 18.11")
    L[-1] += r" & 0 commits & 0 commits & --- \\"
    write("tab_bonus", "\n".join(L) + "\n")


