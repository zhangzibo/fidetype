# ---------------------------------------------------------------- user models: trust vs always commit
def tab_um() -> None:
    c = load("cleanup/results/cleanup.json")["user_models_trust_vs_always_commit"]
    conds = [("b2t-ours", "B2T ours"), ("b2t-published", "B2T publ."), ("emg-calib", "sEMG s.-cal."),
             ("emg-xsession", "sEMG x-sess."), ("emg-xsubject", "sEMG x-subj."), ("meg-async", "MEG")]
    variants = list(c["b2t-ours"].keys())
    vlab = {"symmetric offer (p_miss 0.05, no oracle retype)": "symmetric, miss 0.05", "symmetric offer, p_miss 0.2": "symmetric, miss 0.2",
            "p_miss 0": "miss prob.\\ 0", "p_miss 0.2": "miss prob.\\ 0.2", "selection x0.5": "selection $\\times 0.5$",
            "selection x2": "selection $\\times 2$"}
    L = []
    for v in variants:
        cells = []
        for k, _ in conds:
            x = c[k][v]
            cells.append(f"${x['trust_minus_always_commit']:+.2f}$ \\ci{{{x['ci95'][0]:.2f}}}{{{x['ci95'][1]:.2f}}}")
        L.append(f"{vlab.get(v, v)} & " + " & ".join(cells) + r" \\")
    cnt = []
    for k, _ in conds:
        n = sum(1 for v in variants if c[k][v]["always_commit_faster_than_trust"])
        cnt.append(f"{n} of {len(variants)}")
    L.append(r"\midrule always commit faster & " + " & ".join(cnt) + r" \\")
    write("tab_um_commit", "\n".join(L) + "\n")
    header = " & ".join(n for _, n in conds)
    write("tab_um_commit_head", f"\\textbf{{Variant}} & {header} \\\\\n")


# ---------------------------------------------------------------- controls, guard on (v4-derived) and off (R4 no-guard)
def tab_controls() -> None:
    g = load("v4-derived/results/guard_controls.json")["conditions"]
    n = load("no-guard/results/no_guard_b2t.json")
    L = []
    for which, lab in (("b2t-ours", "ours"), ("b2t-published", "published")):
        rows = [("guard on (frozen v4), LTT max", g[which]["controls"]["split A guard LTT max"]),
                ("guard on, joint LTT $\\beta = 0.10$", g[which]["controls"]["split A guard joint LTT b0.10"]),
                ("guard off (frozen v3), LTT max", n[which]["controls"]["split A LTT max"]),
                ("guard off, plug-in, full fit", n[which]["controls"]["plain threshold (full fit)"])]
        for name, d in rows:
            cells = [f"{d[k]['n_commit']}/{d[k]['n']}" for k in ("real", "other_trial", "frame_shuffled", "uniform")]
            wr = d["uniform"]["wrong_commit_rate"]
            L.append(f"{lab} & {name} & " + " & ".join(cells) + f" & {wr:.2f} \\\\")
    write("tab_controls", "\n".join(L) + "\n")


